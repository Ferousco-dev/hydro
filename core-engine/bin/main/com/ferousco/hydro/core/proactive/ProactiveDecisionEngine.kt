// ============================================================================
// Request
// ============================================================================

/**
 * Everything the proactive stage is allowed to reason about.
 *
 * Both assessments are optional on purpose: a background refresh may only have an observation, only
 * a forecast, or both. Passing `null` is honest about missing data and produces an explicit
 * rationale instead of a guess.
 */
data class ProactiveEvaluationRequest(
    val location: GeoLocation,
    val evaluatedAt: Instant,
    val timeZone: ZoneId,
    val currentAssessment: HeatAssessment? = null,
    val forecastAssessment: HeatAssessment? = null,
    /** The heat category the same forecast carried on the previous evaluation, if any. */
    val previousForecastCategory: NwsHeatIndexCategory? = null,
    /** Planned activity context, when the user has one saved or active. */
    val activityCategory: ActivityCategory? = null,
    val plannedOutdoorMinutes: Int? = null
)

// ============================================================================
// Decision model
// ============================================================================

enum class ProactiveSignalType {
    /** The heat index crosses the NWS "Extreme Caution" threshold or worse. */
    HEAT_THRESHOLD,

    /** The UV index reaches "Very High" or worse. */
    UV_THRESHOLD,

    /** The forecast heat category got worse since the previous evaluation. */
    FORECAST_DETERIORATION
}

/**
 * A deterministic, ready-to-deliver alert.
 *
 * Nothing here is generated by a language model. The title, body, severity, confidence, dedup key,
 * and expiry are all derived from the assessment and the thresholds in
 * [ProactiveDecisionEngine].
 */
data class ProactiveAlert(
    val signal: ProactiveSignalType,
    val category: NotificationCategory,
    val trigger: NotificationTrigger,
    val severity: NotificationSeverity,
    val confidence: Double,
    val title: String,
    val body: String,
    val dedupKey: String,
    val evidence: List<String>,
    val suggestedNextStep: String,
    val validAt: Instant,
    val expiresAt: Instant
) {
    /** Arguments for the `create_notification` tool, so delivery reuses one policy path. */
    fun toToolArguments(timeZone: ZoneId): JsonValue.ObjectValue {
        return JsonValue.ObjectValue(
            linkedMapOf<String, JsonValue>().apply {
                put("title", JsonValue.StringValue(title))
                put("body", JsonValue.StringValue(body))
                put("severity", JsonValue.StringValue(severity.name))
                put("category", JsonValue.StringValue(category.name))
                put("dedup_key", JsonValue.StringValue(dedupKey))
                put("trigger", JsonValue.StringValue(trigger.name))
                put("confidence", SafeJsonCodec.number(confidence))
                put("evidence", JsonValue.ArrayValue(evidence.map(JsonValue::StringValue)))
                put("expires_in_minutes", SafeJsonCodec.number(DEFAULT_EXPIRY_MINUTES))
                put("timezone", JsonValue.StringValue(timeZone.id))
            }
        )
    }

    private companion object {
        /** Matches [ProactiveDecisionEngine.ALERT_RELEVANCE]. */
        const val DEFAULT_EXPIRY_MINUTES = 120L
    }
}

/**
 * The outcome of one evaluation.
 *
 * [alerts] is ordered most-severe first. [rationale] always explains why something was or was not
 * raised, so a quiet notification tray is auditable rather than mysterious.
 */
data class ProactiveDecision(
    val evaluatedAt: Instant,
    val alerts: List<ProactiveAlert>,
    val rationale: List<String>
) {
    val shouldNotify: Boolean get() = alerts.isNotEmpty()
}

// ============================================================================
// Engine
// ============================================================================

/**
 * Deterministic "Evaluate → Decide" stage of Hydro's proactive monitoring loop.
 *
 * This is the part that must not call a language model while the user is idle. It reads only
 * assessments Hydro already computed, applies fixed thresholds, and produces at most one alert per
 * signal type. Delivery, quiet hours, rate limiting, deduplication, and user preferences are applied
 * afterwards by `create_notification`, so there is exactly one policy implementation.
 */
object ProactiveDecisionEngine {

    /** NWS `EXTREME_CAUTION` (severity rank 2) is the first category worth an interruption. */
    const val HEAT_ALERT_MIN_RANK = 2

    /** NWS `DANGER` (rank 3) is escalated to `CRITICAL`, which may bypass quiet hours. */
    const val HEAT_CRITICAL_MIN_RANK = 3

    /** WHO `VERY_HIGH` (rank 3) is the first UV category worth an interruption. */
    const val UV_ALERT_MIN_RANK = 3

    /** How long an alert derived from a valid time stays relevant. */
    val ALERT_RELEVANCE: Duration = Duration.ofHours(2)

    fun evaluate(request: ProactiveEvaluationRequest): ProactiveDecision {
        val rationale = mutableListOf<String>()
        val supported = listOfNotNull(
            request.currentAssessment?.let { "current" to it },
            request.forecastAssessment?.let { "forecast" to it }
        ).filter { (_, assessment) -> assessment is HeatAssessment.Supported }

        if (supported.isEmpty()) {
            rationale += "No supported heat assessment was available; no threshold was evaluated."
            request.currentAssessment?.let {
                rationale += "Current assessment status: ${describeStatus(it)}."
            }
            request.forecastAssessment?.let {
                rationale += "Forecast assessment status: ${describeStatus(it)}."
            }
            return ProactiveDecision(request.evaluatedAt, emptyList(), rationale)
        }

        val alerts = mutableListOf<ProactiveAlert>()

        // ---- Heat threshold -------------------------------------------------
        val heatSource = supported
            .map { (label, assessment) -> label to (assessment as HeatAssessment.Supported) }
            .maxByOrNull { (_, assessment) -> assessment.category.severityRank }

        var heatAlertRaised = false
        if (heatSource != null) {
            val (label, assessment) = heatSource
            if (assessment.category.severityRank >= HEAT_ALERT_MIN_RANK) {
                alerts += heatAlert(request, label, assessment)
                heatAlertRaised = true
                rationale += "Heat index ${formatCelsius(assessment)}°C is ${assessment.category.displayName} " +
                    "($label assessment), at or above the ${categoryName(HEAT_ALERT_MIN_RANK)} threshold."
            } else {
                rationale += "Heat index ${formatCelsius(assessment)}°C is ${assessment.category.displayName}, " +
                    "below the ${categoryName(HEAT_ALERT_MIN_RANK)} notification threshold."
            }
        }

        // ---- UV threshold ---------------------------------------------------
        val uvSource = supported
            .map { (label, assessment) -> label to (assessment as HeatAssessment.Supported) }
            .mapNotNull { (label, assessment) -> assessment.uvCategory?.let { label to (assessment to it) } }
            .maxByOrNull { (_, value) -> value.second.severityRank }

        if (uvSource != null) {
            val (label, value) = uvSource
            val (assessment, uvCategory) = value
            if (uvCategory.severityRank >= UV_ALERT_MIN_RANK) {
                alerts += uvAlert(request, label, assessment, uvCategory)
                rationale += "UV index is ${uvCategory.displayName} ($label assessment), at or above the " +
                    "${categoryName(UV_ALERT_MIN_RANK)} threshold."
            } else {
                rationale += "UV index is ${uvCategory.displayName}, below the notification threshold."
            }
        } else {
            rationale += "No UV index was available, so the UV threshold was not evaluated."
        }

        // ---- Forecast deterioration ----------------------------------------
        val forecast = request.forecastAssessment as? HeatAssessment.Supported
        val previous = request.previousForecastCategory
        if (forecast != null && previous != null) {
            if (forecast.category.severityRank > previous.severityRank) {
                when {
                    heatAlertRaised -> rationale +=
                        "The forecast deteriorated from ${previous.displayName} to " +
                            "${forecast.category.displayName}, but the heat-threshold alert already covers it."
                    // A sub-threshold worsening is only worth an interruption when the user actually
                    // has outdoor plans; otherwise it is noise.
                    request.activityCategory == null -> rationale +=
                        "The forecast deteriorated from ${previous.displayName} to " +
                            "${forecast.category.displayName}, but no planned outdoor activity is recorded, " +
                            "so no alert was raised."
                    else -> {
                        alerts += deteriorationAlert(request, forecast, previous)
                        rationale += "The forecast deteriorated from ${previous.displayName} to " +
                            "${forecast.category.displayName} for a planned activity."
                    }
                }
            } else {
                rationale += "The forecast did not deteriorate (${previous.displayName} → " +
                    "${forecast.category.displayName})."
            }
        }

        val ordered = alerts.sortedWith(
            compareByDescending<ProactiveAlert> { it.severity.ordinal }
                .thenByDescending { it.confidence }
                .thenBy { it.signal.name }
        )
        if (ordered.isEmpty()) {
            rationale += "No alert met the deterministic thresholds; nothing will be sent."
        }
        return ProactiveDecision(request.evaluatedAt, ordered, rationale)
    }

    // ------------------------------------------------------------------
    // Alert builders
    // ------------------------------------------------------------------

    private fun heatAlert(
        request: ProactiveEvaluationRequest,
        label: String,
        assessment: HeatAssessment.Supported
    ): ProactiveAlert {
        val category = assessment.category
        val severity = if (category.severityRank >= HEAT_CRITICAL_MIN_RANK) {
            NotificationSeverity.CRITICAL
        } else {
            NotificationSeverity.WARNING
        }
        val nextStep = when (category) {
            NwsHeatIndexCategory.DANGER,
            NwsHeatIndexCategory.EXTREME_DANGER ->
                "Avoid outdoor exertion during peak heat; move the activity indoors or to a cooler hour."
            else ->
                "Shift outdoor activity earlier or indoors and take frequent water breaks."
        }
        val activity = activityPhrase(request)
        val body = buildString {
            append("Heat index ")
            append(formatCelsius(assessment))
            append("°C (")
            append(category.displayName)
            append(") ")
            append(if (assessment.inputNature == ValueNature.FORECAST) "is forecast" else "was measured")
            append(" near ")
            append(locationLabel(request))
            append(". ")
            if (activity != null) {
                append(activity)
                append(' ')
            }
            append(nextStep)
        }

        return ProactiveAlert(
            signal = ProactiveSignalType.HEAT_THRESHOLD,
            category = NotificationCategory.HEAT,
            trigger = NotificationTrigger.HEAT_THRESHOLD,
            severity = severity,
            confidence = confidenceFor(assessment),
            title = fitTitle("Heat risk: ${category.displayName}"),
            body = fitBody(body),
            dedupKey = "heat:${request.location.cacheCellKey()}:${localDate(request)}",
            evidence = listOf(
                "Heat index ${formatCelsius(assessment)}°C (${category.displayName})",
                "Source: ${assessment.inputSource.providerName} (${label} assessment)",
                "Valid at ${assessment.validAt}",
                category.nwsPublicHealthSummary
            ),
            suggestedNextStep = nextStep,
            validAt = assessment.validAt,
            expiresAt = expiry(assessment.validAt, request.evaluatedAt)
        )
    }

    private fun uvAlert(
        request: ProactiveEvaluationRequest,
        label: String,
        assessment: HeatAssessment.Supported,
        uvCategory: WhoUvCategory
    ): ProactiveAlert {
        val nextStep = when (uvCategory) {
            WhoUvCategory.EXTREME ->
                "Avoid direct midday sun; use protective clothing, a hat, and sunscreen if you must go out."
            else ->
                "Reduce midday sun exposure; protective clothing, a hat, and sunscreen are advised."
        }
        val activity = activityPhrase(request)
        val body = buildString {
            append("UV index is ")
            append(uvCategory.displayName)
            append(" ")
            append(if (assessment.inputNature == ValueNature.FORECAST) "(forecast)" else "(measured)")
            append(" near ")
            append(locationLabel(request))
            append(". ")
            if (activity != null) {
                append(activity)
                append(' ')
            }
            append(nextStep)
        }

        return ProactiveAlert(
            signal = ProactiveSignalType.UV_THRESHOLD,
            category = NotificationCategory.UV,
            trigger = NotificationTrigger.HEAT_THRESHOLD,
            severity = if (uvCategory == WhoUvCategory.EXTREME) {
                NotificationSeverity.CRITICAL
            } else {
                NotificationSeverity.WARNING
            },
            confidence = confidenceFor(assessment),
            title = fitTitle("UV risk: ${uvCategory.displayName}"),
            body = fitBody(body),
            dedupKey = "uv:${request.location.cacheCellKey()}:${localDate(request)}",
            evidence = listOf(
                "UV index category ${uvCategory.displayName}",
                "Source: ${assessment.inputSource.providerName} ($label assessment)",
                uvCategory.guidanceSummary
            ),
            suggestedNextStep = nextStep,
            validAt = assessment.validAt,
            expiresAt = expiry(assessment.validAt, request.evaluatedAt)
        )
    }

    private fun deteriorationAlert(
        request: ProactiveEvaluationRequest,
        forecast: HeatAssessment.Supported,
        previous: NwsHeatIndexCategory
    ): ProactiveAlert {
        val nextStep = "Re-check your plan and consider moving it earlier or indoors."
        val activity = activityPhrase(request)
        val body = buildString {
            append("The heat forecast near ")
            append(locationLabel(request))
            append(" worsened from ")
            append(previous.displayName)
            append(" to ")
            append(forecast.category.displayName)
            append(" (heat index ")
            append(formatCelsius(forecast))
            append("°C). ")
            if (activity != null) {
                append(activity)
                append(' ')
            }
            append(nextStep)
        }

        return ProactiveAlert(
            signal = ProactiveSignalType.FORECAST_DETERIORATION,
            category = NotificationCategory.WEATHER_CHANGE,
            trigger = NotificationTrigger.FORECAST_CHANGE,
            severity = NotificationSeverity.WATCH,
            confidence = confidenceFor(forecast),
            title = fitTitle("Heat forecast worsened: ${forecast.category.displayName}"),
            body = fitBody(body),
            dedupKey = "forecast-change:${request.location.cacheCellKey()}:${localDate(request)}:" +
                forecast.category.name,
            evidence = listOf(
                "Previous forecast category: ${previous.displayName}",
                "New forecast category: ${forecast.category.displayName}",
                "Source: ${forecast.inputSource.providerName}"
            ),
            suggestedNextStep = nextStep,
            validAt = forecast.validAt,
            expiresAt = expiry(forecast.validAt, request.evaluatedAt)
        )
    }

    // ------------------------------------------------------------------
    // Confidence
    // ------------------------------------------------------------------

    /**
     * Confidence describes the *data*, not how alarming the weather is.
     *
     * A stale observation cannot produce a high-confidence alert: it lands below the notification
     * policy's 0.5 floor and is suppressed there, which is the intended behaviour.
     */
    fun confidenceFor(assessment: HeatAssessment.Supported): Double =
        DataConfidence.forInput(assessment.inputNature, assessment.quality.freshnessState)

    // ------------------------------------------------------------------
    // Formatting helpers
    // ------------------------------------------------------------------

    private fun formatCelsius(assessment: HeatAssessment.Supported): String =
        String.format(Locale.US, "%.1f", assessment.heatIndexCelsius.value)

    private fun localDate(request: ProactiveEvaluationRequest): String =
        request.evaluatedAt.atZone(request.timeZone).toLocalDate().toString()

    private fun locationLabel(request: ProactiveEvaluationRequest): String =
        request.location.label?.takeIf { it.isNotBlank() } ?: "your area"

    private fun activityPhrase(request: ProactiveEvaluationRequest): String? {
        val category = request.activityCategory ?: return null
        val minutes = request.plannedOutdoorMinutes ?: return null
        return "Your planned ${minutes}-minute ${category.displayName.lowercase(Locale.US)} is affected."
    }

    private fun expiry(validAt: Instant, evaluatedAt: Instant): Instant =
        validAt.coerceAtLeast(evaluatedAt).plus(ALERT_RELEVANCE)

    private fun describeStatus(assessment: HeatAssessment): String = when (assessment) {
        is HeatAssessment.Supported -> "supported (${assessment.category.displayName})"
        is HeatAssessment.Incomplete -> "incomplete: ${assessment.explanation}"
        is HeatAssessment.Unsupported -> "unsupported: ${assessment.explanation}"
    }

    private fun categoryName(rank: Int): String =
        NwsHeatIndexCategory.entries.firstOrNull { it.severityRank == rank }?.displayName
            ?: WhoUvCategory.entries.firstOrNull { it.severityRank == rank }?.displayName
            ?: "rank $rank"

    /** Android truncates long titles; keep the meaningful part. */
    private fun fitTitle(value: String): String = value.take(MAX_TITLE_CHARS)

    /** The `create_notification` schema caps bodies at 280 characters. */
    private fun fitBody(value: String): String = value.take(MAX_BODY_CHARS)

    private const val MAX_TITLE_CHARS = 80
    private const val MAX_BODY_CHARS = 280
}
