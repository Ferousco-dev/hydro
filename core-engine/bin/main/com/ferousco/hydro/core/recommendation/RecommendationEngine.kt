package com.ferousco.hydro.core.recommendation

import com.ferousco.hydro.core.model.ActivityCategory
import com.ferousco.hydro.core.model.GeoLocation
import com.ferousco.hydro.core.model.HeatAssessment
import com.ferousco.hydro.core.model.NwsHeatIndexCategory
import com.ferousco.hydro.core.model.WhoUvCategory
import com.ferousco.hydro.core.quality.DataConfidence
import java.time.Duration
import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter
import java.util.Locale
import kotlin.math.ceil

// ============================================================================
// Request
// ============================================================================

/**
 * Everything the recommendation stage may reason about.
 *
 * [currentAssessment] is the only required input. Forecast assessments are optional because a
 * refresh may succeed for current conditions and fail for the hourly forecast; the engine then
 * recommends from what it has instead of inventing a trend.
 */
data class RecommendationRequest(
    val location: GeoLocation,
    val evaluatedAt: Instant,
    val timeZone: ZoneId,
    val currentAssessment: HeatAssessment? = null,
    /** Chronologically ordered forecast assessments; order is re-established internally. */
    val forecastAssessments: List<HeatAssessment.Supported> = emptyList(),
    val activityCategory: ActivityCategory? = null,
    val plannedDuration: Duration? = null,
    val lookahead: Duration = Duration.ofHours(12)
) {
    init {
        require(!lookahead.isNegative && !lookahead.isZero) { "lookahead must be positive." }
        require(plannedDuration == null || (!plannedDuration.isNegative && !plannedDuration.isZero)) {
            "plannedDuration must be positive when supplied."
        }
    }
}

// ============================================================================
// Output
// ============================================================================

/**
 * Ordered by seriousness so callers can compare with `maxOf`.
 *
 * [UNKNOWN] is deliberately the lowest value: a stale or missing reading must never outrank a
 * confirmed hazard, and it must not be presented as calm either.
 */
enum class RecommendationUrgency {
    UNKNOWN,
    LOW,
    MODERATE,
    HIGH,
    CRITICAL
}

enum class RecommendedActionKind {
    /** Move the outing indoors or postpone it. */
    POSTPONE_OR_INDOORS,

    /** Keep the outing but shorten exertion and add shade breaks. */
    LIMIT_EXERTION,

    /** Move the outdoor portion into a cooler forecast window. */
    SHIFT_WINDOW,

    /** Plan fluid intake and, for longer outings, a refill point. */
    HYDRATE,

    /** Schedule rest breaks because heat strain accumulates. */
    REST_BREAKS,

    /** Hat, protective clothing, and sunscreen. */
    SUN_PROTECTION,

    /** Stop-and-cool guidance for possible heat illness. */
    MONITOR_SYMPTOMS,

    /** Check on people with less ability to manage heat. */
    CHECK_VULNERABLE,

    /** The reading is too old to rely on; refresh first. */
    REFRESH_DATA,

    /** Tailored note for the recorded activity and duration. */
    ACTIVITY_ADJUSTMENT,

    /** Nothing exceeds a threshold, but conditions can change. */
    MONITOR_CONDITIONS
}

data class RecommendedAction(
    val kind: RecommendedActionKind,
    val title: String,
    val detail: String
)

/**
 * The coolest contiguous forecast span Hydro can support.
 *
 * [peakCategory] and [peakHeatIndexCelsius] describe the worst hour *inside* the window, not the
 * best hour. A window is only useful if its worst hour is tolerable.
 */
data class RecommendationWindow(
    val start: Instant,
    val end: Instant,
    val peakCategory: NwsHeatIndexCategory,
    val peakHeatIndexCelsius: Double,
    val meanHeatIndexCelsius: Double,
    val hoursEvaluated: Int
) {
    fun isCoolerThan(category: NwsHeatIndexCategory, heatIndexCelsius: Double): Boolean =
        peakCategory.severityRank < category.severityRank ||
            (peakCategory == category && peakHeatIndexCelsius < heatIndexCelsius - MEANINGFUL_DELTA_CELSIUS)

    private companion object {
        /** A difference smaller than this is not worth telling someone to reschedule. */
        const val MEANINGFUL_DELTA_CELSIUS = 1.0
    }
}

/**
 * A deterministic, explainable recommendation.
 *
 * Every field is derived from an assessment or a threshold. Nothing here is generated by a language
 * model, and nothing claims a medical guarantee.
 */
data class Recommendation(
    val generatedAt: Instant,
    val validAt: Instant,
    val location: GeoLocation,
    val urgency: RecommendationUrgency,
    val headline: String,
    val summary: String,
    val actions: List<RecommendedAction>,
    val evidence: List<String>,
    val limitations: List<String>,
    val bestWindow: RecommendationWindow?,
    val currentCategory: NwsHeatIndexCategory?,
    val uvCategory: WhoUvCategory?,
    val confidence: Double,
    val isCurrentData: Boolean
) {
    val hasActionableAdvice: Boolean get() = actions.isNotEmpty()
}

// ============================================================================
// Engine
// ============================================================================

/**
 * Deterministic "Recommend action" stage of the product experience.
 *
 * This is the layer between an assessment and a sentence. It decides urgency, picks the coolest
 * supported forecast window, and writes short, concrete next steps. The language model may rephrase
 * the result for chat, but it does not get to invent a different urgency.
 */
object RecommendationEngine {

    /** NWS `EXTREME_CAUTION` is the first category that warrants limiting exposure. */
    const val HEAT_LIMIT_EXERTION_MIN_RANK = 2

    /** NWS `DANGER` warrants postponing or moving indoors. */
    const val HEAT_POSTPONE_MIN_RANK = 3

    /** WHO `VERY_HIGH` is the first UV category that warrants explicit sun protection. */
    const val UV_PROTECTION_MIN_RANK = 3

    /** WHO `EXTREME` is serious enough to raise the overall urgency on its own. */
    const val UV_HIGH_URGENCY_MIN_RANK = 4

    /** Forecast gaps larger than this are not treated as a contiguous window. */
    private val MAX_WINDOW_GAP: Duration = Duration.ofMinutes(90)

    fun recommend(request: RecommendationRequest): Recommendation {
        val current = request.currentAssessment
        if (current !is HeatAssessment.Supported) {
            return unavailableRecommendation(request, current)
        }

        val category = current.category
        val uvCategory = current.uvCategory
        val stale = !DataConfidence.isCurrent(current.quality.freshnessState)
        val confidence = DataConfidence.forInput(
            current.inputNature,
            current.quality.freshnessState
        )

        val bestWindow = bestWindow(request)
        val forecastPeak = forecastPeak(request)

        var urgency = baseUrgency(category)
        if (uvCategory != null) {
            urgency = maxUrgency(urgency, uvUrgency(uvCategory))
        }
        if (forecastPeak != null &&
            forecastPeak.category.severityRank >= HEAT_LIMIT_EXERTION_MIN_RANK &&
            category.severityRank < HEAT_LIMIT_EXERTION_MIN_RANK
        ) {
            urgency = maxUrgency(urgency, RecommendationUrgency.MODERATE)
        }
        // A stale reading cannot support a calm "you're fine" claim.
        if (stale && urgency == RecommendationUrgency.LOW) {
            urgency = RecommendationUrgency.UNKNOWN
        }

        val actions = buildActions(request, current, bestWindow, stale)
        val headline = headlineFor(request, current, urgency, forecastPeak, stale)
        val summary = summaryFor(request, current, urgency, forecastPeak, bestWindow, stale)

        return Recommendation(
            generatedAt = request.evaluatedAt,
            validAt = current.validAt,
            location = request.location,
            urgency = urgency,
            headline = headline,
            summary = summary,
            actions = actions,
            evidence = evidenceFor(request, current, bestWindow, forecastPeak),
            limitations = limitationsFor(request, current, bestWindow, stale),
            bestWindow = bestWindow,
            currentCategory = category,
            uvCategory = uvCategory,
            confidence = confidence,
            isCurrentData = !stale
        )
    }

    // ------------------------------------------------------------------
    // Urgency
    // ------------------------------------------------------------------

    private fun baseUrgency(category: NwsHeatIndexCategory): RecommendationUrgency =
        when {
            category.severityRank >= HEAT_POSTPONE_MIN_RANK -> RecommendationUrgency.CRITICAL
            category.severityRank >= HEAT_LIMIT_EXERTION_MIN_RANK -> RecommendationUrgency.HIGH
            category.severityRank == 1 -> RecommendationUrgency.MODERATE
            else -> RecommendationUrgency.LOW
        }

    private fun uvUrgency(uvCategory: WhoUvCategory): RecommendationUrgency =
        when {
            uvCategory.severityRank >= UV_HIGH_URGENCY_MIN_RANK -> RecommendationUrgency.HIGH
            uvCategory.severityRank >= UV_PROTECTION_MIN_RANK -> RecommendationUrgency.MODERATE
            else -> RecommendationUrgency.LOW
        }

    private fun maxUrgency(
        a: RecommendationUrgency,
        b: RecommendationUrgency
    ): RecommendationUrgency = if (a.ordinal >= b.ordinal) a else b

    // ------------------------------------------------------------------
    // Headline and summary
    // ------------------------------------------------------------------

    private fun headlineFor(
        request: RecommendationRequest,
        current: HeatAssessment.Supported,
        urgency: RecommendationUrgency,
        forecastPeak: HeatAssessment.Supported?,
        stale: Boolean
    ): String = when {
        stale && urgency == RecommendationUrgency.UNKNOWN -> "Refresh before relying on this reading"
        current.category.severityRank >= HEAT_POSTPONE_MIN_RANK -> "Avoid outdoor exertion"
        current.category.severityRank >= HEAT_LIMIT_EXERTION_MIN_RANK -> "Limit outdoor exposure"
        forecastPeak != null &&
            forecastPeak.category.severityRank >= HEAT_LIMIT_EXERTION_MIN_RANK ->
            "Heat builds later"
        current.uvCategory != null &&
            current.uvCategory!!.severityRank >= UV_PROTECTION_MIN_RANK ->
            "Protect against sun exposure"
        current.category.severityRank == 1 -> "Take heat precautions"
        else -> "Below the NWS caution threshold"
    }

    private fun summaryFor(
        request: RecommendationRequest,
        current: HeatAssessment.Supported,
        urgency: RecommendationUrgency,
        forecastPeak: HeatAssessment.Supported?,
        bestWindow: RecommendationWindow?,
        stale: Boolean
    ): String = buildString {
        append("Heat index is ")
        append(formatCelsius(current.heatIndexCelsius.value))
        append(" °C — ")
        append(current.category.displayName)
        append(" — near ")
        append(locationLabel(request.location))
        append(" at ")
        append(formatTime(current.validAt, request.timeZone))
        append(".")

        if (forecastPeak != null &&
            forecastPeak.category.severityRank > current.category.severityRank
        ) {
            append(" The forecast reaches ")
            append(forecastPeak.category.displayName)
            append(" around ")
            append(formatTime(forecastPeak.validAt, request.timeZone))
            append(".")
        }

        if (bestWindow != null &&
            bestWindow.isCoolerThan(current.category, current.heatIndexCelsius.value)
        ) {
            append(" The coolest forecast window is ")
            append(windowLabel(bestWindow, request.timeZone))
            append(" (peak ")
            append(formatCelsius(bestWindow.peakHeatIndexCelsius))
            append(" °C).")
        }

        if (stale) {
            append(" This reading is ")
            append(current.quality.freshnessState.name.replace('_', ' ').lowercase(Locale.US))
            append(" and should be refreshed before you rely on it.")
        }

        append(" This is an ambient heat threshold, not a medical exposure limit.")
    }

    // ------------------------------------------------------------------
    // Actions
    // ------------------------------------------------------------------

    private fun buildActions(
        request: RecommendationRequest,
        current: HeatAssessment.Supported,
        bestWindow: RecommendationWindow?,
        stale: Boolean
    ): List<RecommendedAction> = buildList {
        val category = current.category
        val uv = current.uvCategory

        if (category.severityRank >= HEAT_POSTPONE_MIN_RANK) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.POSTPONE_OR_INDOORS,
                    title = "Move it indoors or postpone",
                    detail = "At this heat index, outdoor exertion is the main thing to avoid. " +
                        "Reschedule if you can; if you cannot, keep the outside portion short and shaded."
                )
            )
        } else if (category.severityRank >= HEAT_LIMIT_EXERTION_MIN_RANK) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.LIMIT_EXERTION,
                    title = "Shorten outdoor exertion",
                    detail = "Keep the activity lighter than planned and take breaks in shade or a cool room."
                )
            )
        }

        if (stale) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.REFRESH_DATA,
                    title = "Refresh the reading first",
                    detail = "The current assessment is ${current.quality.freshnessState.name.replace('_', ' ').lowercase(Locale.US)}. " +
                        "Hydro will not present old data as a current all-clear."
                )
            )
        }

        if (bestWindow != null &&
            bestWindow.isCoolerThan(category, current.heatIndexCelsius.value) &&
            (category.severityRank >= HEAT_LIMIT_EXERTION_MIN_RANK ||
                (forecastPeak(request)?.category?.severityRank ?: 0) >= HEAT_LIMIT_EXERTION_MIN_RANK)
        ) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.SHIFT_WINDOW,
                    title = "Use the coolest window",
                    detail = "${windowLabel(bestWindow, request.timeZone)} has a forecast peak of " +
                        "${formatCelsius(bestWindow.peakHeatIndexCelsius)} °C " +
                        "(${bestWindow.peakCategory.displayName}). Move the outdoor part there if your schedule allows."
                )
            )
        }

        if (category.severityRank >= 1) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.HYDRATE,
                    title = "Plan water, not a fixed guarantee",
                    detail = "Drink before you go out and carry water for anything longer than an hour. " +
                        "Needs vary by person, exertion, and conditions."
                )
            )
        }

        if (category.severityRank >= HEAT_LIMIT_EXERTION_MIN_RANK) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.REST_BREAKS,
                    title = "Schedule rest breaks",
                    detail = "Heat strain accumulates. Build shade or indoor breaks into the outing instead of " +
                        "waiting until you feel unwell."
                )
            )
        }

        if (uv != null && uv.severityRank >= UV_PROTECTION_MIN_RANK) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.SUN_PROTECTION,
                    title = "Protect against UV",
                    detail = "UV is ${uv.displayName}. Use a hat, protective clothing, and sunscreen; " +
                        "reduce direct midday sun where possible."
                )
            )
        }

        if (category.severityRank >= HEAT_POSTPONE_MIN_RANK) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.MONITOR_SYMPTOMS,
                    title = "Stop if symptoms appear",
                    detail = "Dizziness, confusion, headache, or stopping sweating are reasons to cool down " +
                        "immediately. Severe symptoms need urgent help."
                )
            )
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.CHECK_VULNERABLE,
                    title = "Check on people at higher risk",
                    detail = "Older adults, young children, and anyone without reliable cooling are affected first."
                )
            )
        }

        val activity = request.activityCategory
        val duration = request.plannedDuration
        if (activity != null && category.severityRank >= 1) {
            val durationText = duration?.let { " ${it.toMinutes()}-minute" } ?: ""
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.ACTIVITY_ADJUSTMENT,
                    title = "Adjust the planned ${activity.displayName.lowercase(Locale.US)}",
                    detail = "For your$durationText ${activity.displayName.lowercase(Locale.US)}, use the guidance above " +
                        "rather than the same plan you would follow in cooler weather."
                )
            )
        }

        if (isEmpty()) {
            add(
                RecommendedAction(
                    kind = RecommendedActionKind.MONITOR_CONDITIONS,
                    title = "Re-check before a long outing",
                    detail = "Nothing currently exceeds the NWS caution or WHO UV thresholds, but conditions can " +
                        "change. Refresh before you commit to a long outdoor plan."
                )
            )
        }
    }

    // ------------------------------------------------------------------
    // Forecast window
    // ------------------------------------------------------------------

    /**
     * Picks the contiguous forecast span with the lowest peak severity, then the lowest peak heat
     * index. With a planned duration, the span must cover it; otherwise a single hour is enough.
     *
     * Returns `null` rather than stretching across missing hours, because a gap means Hydro does not
     * know what happens in between.
     */
    fun bestWindow(request: RecommendationRequest): RecommendationWindow? {
        val horizonEnd = request.evaluatedAt.plus(request.lookahead)
        val points = request.forecastAssessments
            .filter { !it.validAt.isBefore(request.evaluatedAt) && !it.validAt.isAfter(horizonEnd) }
            .sortedBy { it.validAt }
        if (points.isEmpty()) return null

        val requiredHours = request.plannedDuration
            ?.let { ceil(it.toMinutes() / 60.0).toInt().coerceAtLeast(1) }
            ?: 1
        if (points.size < requiredHours) return null

        val candidates = mutableListOf<List<HeatAssessment.Supported>>()
        for (start in 0..points.size - requiredHours) {
            val slice = points.subList(start, start + requiredHours)
            val contiguous = slice.zipWithNext().all { (earlier, later) ->
                Duration.between(earlier.validAt, later.validAt) <= MAX_WINDOW_GAP
            }
            if (contiguous) candidates += slice
        }
        if (candidates.isEmpty()) return null

        val best = candidates.minWithOrNull(
            compareBy<List<HeatAssessment.Supported>>(
                { window -> window.maxOf { it.category.severityRank } },
                { window -> window.maxOf { it.heatIndexCelsius.value } }
            )
        ) ?: return null

        val peak = best.maxByOrNull { it.heatIndexCelsius.value } ?: return null
        return RecommendationWindow(
            start = best.first().validAt,
            end = best.last().validAt.plus(Duration.ofHours(1)),
            peakCategory = peak.category,
            peakHeatIndexCelsius = peak.heatIndexCelsius.value,
            meanHeatIndexCelsius = best.map { it.heatIndexCelsius.value }.average(),
            hoursEvaluated = best.size
        )
    }

    private fun forecastPeak(request: RecommendationRequest): HeatAssessment.Supported? =
        request.forecastAssessments
            .filter { it.validAt.isAfter(request.evaluatedAt) }
            .maxWithOrNull(
                compareBy<HeatAssessment.Supported> { it.category.severityRank }
                    .thenBy { it.heatIndexCelsius.value }
            )

    // ------------------------------------------------------------------
    // Evidence and limitations
    // ------------------------------------------------------------------

    private fun evidenceFor(
        request: RecommendationRequest,
        current: HeatAssessment.Supported,
        bestWindow: RecommendationWindow?,
        forecastPeak: HeatAssessment.Supported?
    ): List<String> = buildList {
        add(
            "Heat index ${formatCelsius(current.heatIndexCelsius.value)} °C — " +
                "${current.category.displayName} (${current.inputNature.name}, " +
                "${current.quality.freshnessState.name})"
        )
        current.uvCategory?.let { add("UV index category ${it.displayName}") }
        add("Source: ${current.inputSource.providerName}")
        forecastPeak?.let {
            add(
                "Forecast peak: ${it.category.displayName} around " +
                    "${formatTime(it.validAt, request.timeZone)}"
            )
        }
        bestWindow?.let {
            add(
                "Coolest window: ${windowLabel(it, request.timeZone)}, peak " +
                    "${formatCelsius(it.peakHeatIndexCelsius)} °C (${it.peakCategory.displayName})"
            )
        }
        add("Assessed at ${current.assessedAt}")
    }

    private fun limitationsFor(
        request: RecommendationRequest,
        current: HeatAssessment.Supported,
        bestWindow: RecommendationWindow?,
        stale: Boolean
    ): List<String> = buildList {
        add(
            "Recommendations apply fixed NWS and WHO thresholds to ambient conditions; they are not " +
                "personalised medical advice."
        )
        if (current.uvCategory == null) {
            add("UV index was unavailable, so sun-protection guidance reflects heat only.")
        }
        if (stale) {
            add("The current assessment is ${current.quality.freshnessState.name}; refresh before acting on it.")
        }
        if (bestWindow == null) {
            add("No usable forecast coverage was available, so no cooler window could be recommended.")
        }
        if (request.activityCategory == null) {
            add("No activity was supplied, so guidance is general rather than tailored to exertion.")
        }
        addAll(current.limitations.take(3))
    }

    // ------------------------------------------------------------------
    // Unavailable
    // ------------------------------------------------------------------

    private fun unavailableRecommendation(
        request: RecommendationRequest,
        assessment: HeatAssessment?
    ): Recommendation {
        val explanation = when (assessment) {
            is HeatAssessment.Supported -> assessment.explanation
            is HeatAssessment.Incomplete -> assessment.explanation
            is HeatAssessment.Unsupported -> assessment.explanation
            null -> "No current heat assessment was supplied."
        }
        val limitations = buildList {
            add("Hydro will not recommend an action without a supported assessment.")
            assessment?.limitations?.take(3)?.forEach { add(it) }
        }
        return Recommendation(
            generatedAt = request.evaluatedAt,
            validAt = assessment?.validAt ?: request.evaluatedAt,
            location = request.location,
            urgency = RecommendationUrgency.UNKNOWN,
            headline = "Current conditions are unavailable",
            summary = explanation,
            actions = listOf(
                RecommendedAction(
                    kind = RecommendedActionKind.REFRESH_DATA,
                    title = "Refresh before making a heat decision",
                    detail = "The assessment is missing required inputs, so Hydro has no grounded action to give."
                )
            ),
            evidence = emptyList(),
            limitations = limitations,
            bestWindow = null,
            currentCategory = null,
            uvCategory = null,
            confidence = 0.0,
            isCurrentData = false
        )
    }

    // ------------------------------------------------------------------
    // Formatting
    // ------------------------------------------------------------------

    private fun formatCelsius(value: Double): String =
        String.format(Locale.US, "%.1f", value)

    private fun formatTime(instant: Instant, zone: ZoneId): String =
        TIME_FORMAT.withZone(zone).format(instant)

    private fun windowLabel(window: RecommendationWindow, zone: ZoneId): String {
        val startLocal = window.start.atZone(zone)
        val endLocal = window.end.atZone(zone)
        val suffix = if (startLocal.toLocalDate() != endLocal.toLocalDate()) " (+1 day)" else ""
        return "${formatTime(window.start, zone)}–${formatTime(window.end, zone)}$suffix"
    }

    private fun locationLabel(location: GeoLocation): String =
        location.label?.takeIf { it.isNotBlank() } ?: "your area"

    private val TIME_FORMAT: DateTimeFormatter = DateTimeFormatter.ofPattern("HH:mm", Locale.US)
}
