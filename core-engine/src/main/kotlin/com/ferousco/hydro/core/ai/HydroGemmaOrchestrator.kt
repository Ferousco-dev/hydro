data class ExecutedToolTrace(
    val round: Int,
    val toolName: String,
    val succeeded: Boolean,
    val errorCode: String? = null,
    val durationMillis: Long
)

data class GroundingSummary(
    val modelId: String,
    val activeBackend: LlmHardwareBackend,
    val modalityMode: LlmModalityMode,
    val executedTools: List<ExecutedToolTrace>,
    val attributions: Set<String>,
    val usedCachedWeather: Boolean,
    val usedForecastData: Boolean,
    val usedModelAssimilatedCurrent: Boolean,
    val missingVariablesReported: Set<String>
)

sealed interface HydroAssistantOutcome {
    /**
     * Completed grounded response generated by Gemma 3n using deterministic Hydro tool results.
     */
    data class Responded(
        val responseText: String,
        val grounding: GroundingSummary
    ) : HydroAssistantOutcome

    /**
     * Model weights (`gemma-3n-E2B-it-int4.litertlm`) are not installed or device RAM is insufficient;
     * deterministic `HydroEngine` remains fully usable without the language model.
     */
    data class ModelUnavailable(
        val readiness: ModelArtifactReadiness,
        val message: String
    ) : HydroAssistantOutcome

    /**
     * Inference or orchestration failed (for example, tool round budget exhausted or runtime error).
     */
    data class Failed(
        val error: EngineError,
        val partialToolTraces: List<ExecutedToolTrace>
    ) : HydroAssistantOutcome
}

data class HydroGemmaOrchestratorConfig(
    val maxToolRounds: Int = 4,
    val maxToolCallsPerRound: Int = 3,
    val maxOutputTokensPerTurn: Int = 640,
    val sampling: LlmSamplingParams = LlmSamplingParams.GROUNDED_HYDRO,
    val embedToolCatalogInSystemPrompt: Boolean = true
) {
    init {
        require(maxToolRounds in 1..8) { "maxToolRounds must be in 1..8." }
        require(maxToolCallsPerRound in 1..6) { "maxToolCallsPerRound must be in 1..6." }
        require(maxOutputTokensPerTurn in 64..2048) { "maxOutputTokensPerTurn must be in 64..2048." }
    }
}

/**
 * Coordinates on-device `google/gemma-3n-E2B-it-litert-lm` intent interpretation and natural-language
 * explanation with Hydro's deterministic [HydroToolRegistry].
 *
 * Architectural guarantees:
 * 1. **Zero LLM arithmetic**: System instructions and tool routing keep all weather lookup, unit
 *    normalization, NOAA/NWS Heat Index calculation, candidate window ranking, and historical deltas
 *    strictly inside `HydroToolRegistry`.
 * 2. **Dual tool-calling compatibility**: Supports both LiteRT-LM native `ToolCall` responses and
 *    prompt-structured JSON `{"tool_call": {"name": "...", "arguments": {...}}}` blocks so
 *    `gemma-3n-E2B-it-int4.litertlm` works reliably across LiteRT-LM runtime versions.
 * 3. **4K context discipline**: Keeps system instructions and tool declarations compact so multi-step
 *    tool execution fits cleanly inside Gemma 3n's 4,096-token Android LiteRT-LM context window.
 * 4. **Grounded provenance tracking**: Inspects tool JSON outputs to record Open-Meteo CC-BY 4.0
 *    attribution, cached-vs-live delivery, forecast-vs-observation provenance, and missing variables.
 */
class HydroGemmaOrchestrator(
    private val llmClient: OnDeviceLlmClient,
    private val toolRegistry: HydroToolRegistry,
    private val config: HydroGemmaOrchestratorConfig = HydroGemmaOrchestratorConfig(),
    private val clock: Clock = Clock.systemUTC(),
    private val logger: DiagnosticLogger = NoOpDiagnosticLogger
) {
    suspend fun respond(
        userPrompt: String,
        additionalMedia: List<LlmInputContent> = emptyList(),
        userLocationContext: GeoLocation? = null,
        permissionGate: ToolPermissionGate = AllowAllToolPermissionGate
    ): HydroAssistantOutcome {
        currentCoroutineContext().ensureActive()
        if (userPrompt.isBlank()) {
            return HydroAssistantOutcome.Failed(
                error = EngineError.InvalidInput("userPrompt", "blank", "User prompt must not be blank."),
                partialToolTraces = emptyList()
            )
        }

        when (val readiness = llmClient.checkArtifactReadiness()) {
            is ModelArtifactReadiness.Ready -> Unit
            is ModelArtifactReadiness.NotInstalled -> {
                return HydroAssistantOutcome.ModelUnavailable(
                    readiness = readiness,
                    message = readiness.provisioningHint
                )
            }
            is ModelArtifactReadiness.InvalidArtifact -> {
                return HydroAssistantOutcome.ModelUnavailable(
                    readiness = readiness,
                    message = readiness.reason
                )
            }
            is ModelArtifactReadiness.InsufficientDeviceMemory -> {
                return HydroAssistantOutcome.ModelUnavailable(
                    readiness = readiness,
                    message = "${readiness.modelSpec.displayName} requires ${readiness.requiredRamGb} GB RAM " +
                        "(detected ${"%.1f".format(java.util.Locale.US, readiness.detectedRamGb)} GB)."
                )
            }
        }

        val activeRuntime = llmClient.activeRuntimeInfoOrNull()
            ?: when (val initRes = llmClient.initialize()) {
                is EngineResult.Success -> initRes.value
                is EngineResult.Failure -> return HydroAssistantOutcome.Failed(initRes.error, emptyList())
            }

        if (additionalMedia.isNotEmpty() && activeRuntime.modalityMode == LlmModalityMode.TEXT_ONLY) {
            return HydroAssistantOutcome.Failed(
                error = EngineError.UnsupportedCalculation(
                    methodId = activeRuntime.modelSpec.huggingFaceRepoId,
                    reason = "MULTIMODAL_BACKEND_FALLBACK_TEXT_ONLY",
                    message = "Gemma 3n initialized in text-only CPU fallback mode; image/audio inputs cannot be processed in this session."
                ),
                partialToolTraces = emptyList()
            )
        }

        val systemInstruction = buildGroundedSystemPrompt(
            nowUtc = clock.instant(),
            userLocationContext = userLocationContext
        )

        val initialContents = buildList {
            add(LlmInputContent.Text(userPrompt.trim()))
            addAll(additionalMedia.filterNot { it is LlmInputContent.Text })
        }.orderedTextFirstForLiteRt()

        val conversationHistory = mutableListOf(
            LlmConversationMessage.userMultimodal(initialContents)
        )

        val traces = mutableListOf<ExecutedToolTrace>()
        val attributions = linkedSetOf<String>()
        val missingVariables = linkedSetOf<String>()
        var usedCache = false
        var usedForecast = false
        var usedModelAssimilated = false

        for (round in 1..config.maxToolRounds) {
            currentCoroutineContext().ensureActive()

            val genResponse = when (
                val genResult = llmClient.generate(
                    LlmGenerationRequest(
                        systemInstruction = systemInstruction,
                        messages = conversationHistory.toList(),
                        sampling = config.sampling,
                        maxOutputTokens = config.maxOutputTokensPerTurn,
                        enableNativeToolDeclarations = true
                    )
                )
            ) {
                is EngineResult.Success -> genResult.value
                is EngineResult.Failure -> return HydroAssistantOutcome.Failed(genResult.error, traces.toList())
            }

            val requestedCalls = extractRequestedToolCalls(genResponse)
            if (requestedCalls.isEmpty()) {
                val cleanedAnswer = genResponse.text.trim()
                if (cleanedAnswer.isEmpty()) {
                    return HydroAssistantOutcome.Failed(
                        error = EngineError.InvalidResponse(
                            providerId = activeRuntime.modelSpec.huggingFaceRepoId,
                            fieldOrStage = "empty_model_output",
                            message = "On-device model returned an empty response."
                        ),
                        partialToolTraces = traces.toList()
                    )
                }

                return HydroAssistantOutcome.Responded(
                    responseText = appendMandatoryProvenanceNoticeIfNeeded(
                        answer = cleanedAnswer,
                        attributions = attributions,
                        usedCache = usedCache
                    ),
                    grounding = GroundingSummary(
                        modelId = activeRuntime.modelSpec.huggingFaceRepoId,
                        activeBackend = genResponse.runtimeInfo.activeBackend,
                        modalityMode = genResponse.runtimeInfo.modalityMode,
                        executedTools = traces.toList(),
                        attributions = attributions.toSet(),
                        usedCachedWeather = usedCache,
                        usedForecastData = usedForecast,
                        usedModelAssimilatedCurrent = usedModelAssimilated,
                        missingVariablesReported = missingVariables.toSet()
                    )
                )
            }

            conversationHistory.add(
                LlmConversationMessage.modelText(
                    text = genResponse.text,
                    toolCalls = genResponse.nativeToolCalls
                )
            )

            val boundedCalls = requestedCalls.take(config.maxToolCallsPerRound)
            for (call in boundedCalls) {
                val startNs = System.nanoTime()
                val outcome = when (call) {
                    is ParsedToolRequest.Valid -> toolRegistry.execute(
                        toolName = call.toolName,
                        rawArguments = call.arguments,
                        permissionGate = permissionGate
                    )
                    is ParsedToolRequest.Malformed -> ToolCallOutcome.Failure(
                        toolName = call.rawToolName ?: "invalid_tool_call",
                        errorCode = "INVALID_TOOL_CALL_SYNTAX",
                        error = EngineError.InvalidInput(
                            field = "tool_call",
                            rejectedValueSummary = "malformed_json_tool_call",
                            message = call.reason
                        ),
                        retryable = false,
                        jsonError = JsonValue.ObjectValue(
                            linkedMapOf(
                                "ok" to JsonValue.BooleanValue(false),
                                "error_code" to JsonValue.StringValue("INVALID_TOOL_CALL_SYNTAX"),
                                "message" to JsonValue.StringValue(call.reason)
                            )
                        )
                    )
                }
                val elapsedMs = (System.nanoTime() - startNs) / 1_000_000L

                when (outcome) {
                    is ToolCallOutcome.Success -> {
                        traces.add(
                            ExecutedToolTrace(
                                round = round,
                                toolName = outcome.toolName,
                                succeeded = true,
                                durationMillis = elapsedMs
                            )
                        )
                        inspectToolResultProvenance(
                            toolName = outcome.toolName,
                            json = outcome.jsonResult,
                            attributions = attributions,
                            missingVariables = missingVariables,
                            onCacheDetected = { usedCache = true },
                            onForecastDetected = { usedForecast = true },
                            onModelAssimilatedDetected = { usedModelAssimilated = true }
                        )
                        conversationHistory.add(
                            LlmConversationMessage.toolResponse(outcome.toolName, outcome.jsonResult)
                        )
                    }
                    is ToolCallOutcome.Failure -> {
                        traces.add(
                            ExecutedToolTrace(
                                round = round,
                                toolName = outcome.toolName,
                                succeeded = false,
                                errorCode = outcome.errorCode,
                                durationMillis = elapsedMs
                            )
                        )
                        conversationHistory.add(
                            LlmConversationMessage.toolResponse(outcome.toolName, outcome.jsonError)
                        )
                    }
                }
            }
        }

        logger.warn(
            COMPONENT,
            "Exceeded maxToolRounds without final natural-language answer",
            mapOf("maxToolRounds" to config.maxToolRounds.toString(), "traceCount" to traces.size.toString())
        )
        return HydroAssistantOutcome.Failed(
            error = EngineError.ProviderError(
                providerId = activeRuntime.modelSpec.huggingFaceRepoId,
                statusCode = null,
                providerReason = "tool_round_limit_exceeded",
                isTransient = false,
                message = "Gemma 3n exceeded maximum tool-calling rounds (${config.maxToolRounds}) without producing a final response."
            ),
            partialToolTraces = traces.toList()
        )
    }

    fun buildGroundedSystemPrompt(
        nowUtc: Instant = clock.instant(),
        userLocationContext: GeoLocation? = null
    ): String = buildString {
        appendLine("You are Hydro's on-device environmental intelligence assistant running on Gemma 3n.")
        appendLine("Current UTC timestamp: $nowUtc.")
        if (userLocationContext != null) {
            appendLine(
                "Active user coordinates for tool calls only: latitude=${userLocationContext.latitude}, " +
                    "longitude=${userLocationContext.longitude}" +
                    (userLocationContext.timeZone?.let { ", timeZone=${it.id}" } ?: "") + "."
            )
        }
        appendLine("STRICT SCIENTIFIC & SAFETY RULES:")
        appendLine("1. NEVER invent weather values, Heat Index numbers, UV values, shade, route conditions, or personal physiological thresholds.")
        appendLine("2. NEVER perform mental math for Heat Index, unit conversions, or window rankings; ALWAYS call Hydro tools.")
        appendLine("3. Distinguish clearly between observed conditions, model-assimilated current values, and forecasts.")
        appendLine("4. If data is served from cache or variables are unavailable, explicitly tell the user; never claim cached data is live.")
        appendLine("5. NEVER declare an outdoor activity 'safe' solely because one departure window is cooler than another.")
        if (config.embedToolCatalogInSystemPrompt) {
            appendLine("TOOL CALL PROTOCOL:")
            appendLine("When you need environmental data or deterministic calculations, output ONLY a JSON object in this exact form:")
            appendLine("""{"tool_call":{"name":"<tool_name>","arguments":{...}}}""")
            appendLine("Available tools (OpenAPI JSON Schema):")
            appendLine(toolRegistry.exportOpenApiToolsJson())
        }
    }

    private sealed interface ParsedToolRequest {
        data class Valid(val toolName: String, val arguments: JsonValue.ObjectValue) : ParsedToolRequest
        data class Malformed(val rawToolName: String?, val reason: String) : ParsedToolRequest
    }

    private fun extractRequestedToolCalls(response: LlmGenerationResponse): List<ParsedToolRequest> {
        if (response.nativeToolCalls.isNotEmpty()) {
            return response.nativeToolCalls.map { ParsedToolRequest.Valid(it.toolName, it.arguments) }
        }

        val trimmed = response.text.trim()
        val jsonCandidate = extractToolCallJsonCandidate(trimmed) ?: return emptyList()
        val parsed = SafeJsonCodec.parse(
            input = jsonCandidate,
            sourceName = "gemma_tool_call",
            maxChars = HydroToolRegistry.MAX_TOOL_ARGUMENT_JSON_CHARS,
            maxDepth = HydroToolRegistry.MAX_TOOL_ARGUMENT_JSON_DEPTH
        )
        val rootObj = when (parsed) {
            is EngineResult.Failure -> return listOf(
                ParsedToolRequest.Malformed(null, "Malformed tool_call JSON from model: ${parsed.error.message}")
            )
            is EngineResult.Success -> parsed.value as? JsonValue.ObjectValue
                ?: return listOf(ParsedToolRequest.Malformed(null, "Expected JSON object for tool_call."))
        }

        val callObj = rootObj.getObject("tool_call") ?: rootObj
        val name = callObj.getString("name")
            ?: return listOf(ParsedToolRequest.Malformed(null, "Missing string 'name' in tool_call JSON."))
        val args = callObj.getObject("arguments") ?: JsonValue.ObjectValue(emptyMap())
        return listOf(ParsedToolRequest.Valid(name, args))
    }

    private fun extractToolCallJsonCandidate(text: String): String? {
        // 1. Fenced ```tool_call ... ``` or ```json ... ``` containing "tool_call"
        val fenceMatch = FENCED_BLOCK_REGEX.find(text)
        if (fenceMatch != null) {
            val tag = fenceMatch.groupValues[1].lowercase()
            val body = fenceMatch.groupValues[2].trim()
            if (tag == "tool_call" || body.contains("\"tool_call\"")) {
                return body
            }
        }
        // 2. Direct JSON object starting with { and containing "tool_call"
        if (text.startsWith("{") && text.endsWith("}") && text.contains("\"tool_call\"")) {
            return text
        }
        return null
    }

    private fun inspectToolResultProvenance(
        toolName: String,
        json: JsonValue.ObjectValue,
        attributions: MutableSet<String>,
        missingVariables: MutableSet<String>,
        onCacheDetected: () -> Unit,
        onForecastDetected: () -> Unit,
        onModelAssimilatedDetected: () -> Unit
    ) {
        if (toolName == "get_hourly_forecast" || toolName == "compare_forecast_periods") {
            onForecastDetected()
        }
        if (json.getString("data_nature") == "FORECAST") {
            onForecastDetected()
        }
        if (json.getString("observation_kind") == "MODEL_ASSIMILATED_CURRENT") {
            onModelAssimilatedDetected()
        }
        json.getObject("source")?.getString("attribution")?.let { attributions.add(it) }
        val freshness = json.getObject("freshness")
        if (freshness?.getString("delivery_origin") == "LOCAL_CACHE" ||
            freshness?.getBoolean("is_current_and_live") == false && freshness.getString("delivery_origin") == "LOCAL_CACHE"
        ) {
            onCacheDetected()
        }
        json.getArray("missing_information")?.items?.forEach { item ->
            when (item) {
                is JsonValue.StringValue -> missingVariables.add(item.value)
                is JsonValue.ObjectValue -> item.getString("variable")?.let { missingVariables.add(it) }
                else -> Unit
            }
        }
        json.getObject("variables")?.entries?.forEach { (varName, varVal) ->
            val obj = varVal as? JsonValue.ObjectValue
            if (obj?.getBoolean("available") == false) {
                missingVariables.add(varName)
            }
        }
    }

    private fun appendMandatoryProvenanceNoticeIfNeeded(
        answer: String,
        attributions: Set<String>,
        usedCache: Boolean
    ): String {
        val notes = mutableListOf<String>()
        if (usedCache && !answer.contains("cache", ignoreCase = true)) {
            notes.add("Note: Weather inputs were served from local cache rather than a live network fetch.")
        }
        for (attr in attributions) {
            if (!answer.contains("Open-Meteo", ignoreCase = true) && attr.contains("Open-Meteo", ignoreCase = true)) {
                notes.add("Source: $attr.")
            }
        }
        return if (notes.isEmpty()) answer else "$answer\n\n(${notes.joinToString(" ")})"
    }

    companion object {
        private const val COMPONENT = "HydroGemmaOrchestrator"
        private val FENCED_BLOCK_REGEX = Regex("```([a-zA-Z0-9_-]*)\\s*([\\s\\S]*?)```")
    }
}
